<?php

namespace App\Services;

use Exception;
use Illuminate\Database\Connection;
use Throwable;

class PhpDatabaseDumper
{
    public function dumpToStream(Connection $connection, $stream): void
    {
        $driver = $connection->getDriverName();
        if (in_array($driver, ['mysql', 'mariadb'], true)) {
            $this->dumpMysql($connection, $stream);
            return;
        }
        if ($driver === 'sqlite') {
            $this->dumpSqlite($connection, $stream);
            return;
        }

        throw new Exception('Database backup is not supported for the configured [' . $driver . '] driver.');
    }

    private function dumpMysql(Connection $connection, $stream): void
    {
        $connection->beginTransaction();

        try {
            $objects = $connection->selectOne(<<<'SQL'
                SELECT
                    (SELECT COUNT(*) FROM information_schema.VIEWS WHERE TABLE_SCHEMA = DATABASE()) AS view_count,
                    (SELECT COUNT(*) FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = DATABASE()) AS trigger_count,
                    (SELECT COUNT(*) FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA = DATABASE()) AS routine_count,
                    (SELECT COUNT(*) FROM information_schema.EVENTS WHERE EVENT_SCHEMA = DATABASE()) AS event_count
                SQL);

            if (array_sum(array_map('intval', (array) $objects)) > 0) {
                throw new Exception('This PHP backup supports tables and rows only; views, triggers, routines, or events exist, so no incomplete backup was created.');
            }

            $tables = [];
            foreach ($connection->select('SHOW FULL TABLES') as $tableRow) {
                $values = array_values((array) $tableRow);
                $tableType = strtoupper((string) ($values[1] ?? ''));
                if ($tableType !== 'BASE TABLE') {
                    throw new Exception("Database object type [$tableType] is not supported by this PHP backup; no incomplete backup was created.");
                }
                if (isset($values[0])) {
                    $tables[] = (string) $values[0];
                }
            }

            $this->write($stream, "-- Database backup generated by the application\nSET FOREIGN_KEY_CHECKS=0;\n");
            foreach ($tables as $table) {
                $this->write($stream, 'DROP TABLE IF EXISTS ' . $this->mysqlIdentifier($table) . ";\n");
            }

            foreach ($tables as $table) {
                $createRows = $connection->select('SHOW CREATE TABLE ' . $this->mysqlIdentifier($table));
                $values = isset($createRows[0]) ? (array) $createRows[0] : [];
                $createSql = $values['Create Table'] ?? array_values($values)[1] ?? null;
                if (!is_string($createSql) || trim($createSql) === '') {
                    throw new Exception("Unable to read the schema for table [$table].");
                }
                $this->write($stream, $createSql . ";\n");
            }

            foreach ($tables as $table) {
                $columnRows = $connection->select('SHOW FULL COLUMNS FROM ' . $this->mysqlIdentifier($table));
                $columns = [];
                foreach ($columnRows as $columnRow) {
                    $column = (array) $columnRow;
                    $extra = (string) ($column['Extra'] ?? '');
                    if (stripos($extra, 'INVISIBLE') !== false) {
                        throw new Exception("Invisible columns are not supported in table [{$table}]; no incomplete backup was created.");
                    }
                    if (preg_match('/(?:VIRTUAL|STORED)\s+GENERATED/i', $extra)) {
                        continue;
                    }
                    $columns[] = [
                        'name' => (string) ($column['Field'] ?? ''),
                        'type' => (string) ($column['Type'] ?? ''),
                    ];
                }
                $this->dumpTableRows($connection, $stream, $table, $columns, 'mysql');
            }

            $this->write($stream, "SET FOREIGN_KEY_CHECKS=1;\n");
            $connection->commit();
        } catch (Throwable $e) {
            if ($connection->transactionLevel() > 0) {
                $connection->rollBack();
            }
            throw $e;
        }
    }

    private function dumpSqlite(Connection $connection, $stream): void
    {
        $objects = $connection->select("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND type IN ('table', 'view', 'index', 'trigger') ORDER BY type, name");
        $tables = array_values(array_filter($objects, static fn ($object) => $object->type === 'table'));
        $otherObjects = array_values(array_filter($objects, static fn ($object) => $object->type !== 'table'));

        $this->write($stream, "-- SQLite database backup generated by the application\nPRAGMA foreign_keys=OFF;\n");
        foreach ($otherObjects as $object) {
            $drop = match ($object->type) {
                'view' => 'DROP VIEW IF EXISTS ',
                'index' => 'DROP INDEX IF EXISTS ',
                'trigger' => 'DROP TRIGGER IF EXISTS ',
                default => null,
            };
            if ($drop !== null) {
                $this->write($stream, $drop . $this->sqliteIdentifier((string) $object->name) . ";\n");
            }
        }
        foreach ($tables as $table) {
            $this->write($stream, 'DROP TABLE IF EXISTS ' . $this->sqliteIdentifier((string) $table->name) . ";\n");
        }
        foreach ($tables as $table) {
            $this->write($stream, $table->sql . ";\n");
        }
        foreach ($tables as $table) {
            $metadata = $connection->select('PRAGMA table_info(' . $this->sqliteIdentifier((string) $table->name) . ')');
            $columns = array_map(static fn ($column) => [
                'name' => (string) $column->name,
                'type' => (string) $column->type,
            ], $metadata);
            $this->dumpTableRows($connection, $stream, (string) $table->name, $columns, 'sqlite');
        }
        foreach ($otherObjects as $object) {
            $this->write($stream, $object->sql . ";\n");
        }
        $this->write($stream, "PRAGMA foreign_keys=ON;\n");
    }

    private function dumpTableRows(Connection $connection, $stream, string $table, array $columns, string $driver): void
    {
        if ($columns === []) {
            $count = (int) ($connection->selectOne('SELECT COUNT(*) AS aggregate FROM ' . $this->identifier($table, $driver))->aggregate ?? 0);
            if ($count > 0) {
                throw new Exception("Table [$table] has rows but no insertable columns; backup was aborted.");
            }
            return;
        }

        $quotedTable = $this->identifier($table, $driver);
        $quotedColumns = array_map(fn (array $column) => $this->identifier($column['name'], $driver), $columns);
        $select = 'SELECT ' . implode(', ', $quotedColumns) . ' FROM ' . $quotedTable;

        foreach ($connection->cursor($select, [], false) as $row) {
            $rowValues = (array) $row;
            $values = [];
            foreach ($columns as $column) {
                $values[] = $this->value($connection, $rowValues[$column['name']] ?? null, (string) $column['type'], $driver);
            }
            $this->write($stream, 'INSERT INTO ' . $quotedTable . ' (' . implode(', ', $quotedColumns) . ') VALUES (' . implode(', ', $values) . ");\n");
        }
    }

    private function value(Connection $connection, mixed $value, string $type, string $driver): string
    {
        if ($value === null) {
            return 'NULL';
        }
        if (is_resource($value)) {
            $value = stream_get_contents($value);
            if ($value === false) {
                throw new Exception('Unable to read a binary database value for the backup.');
            }
        }

        $value = (string) $value;
        if (preg_match('/(?:blob|binary|varbinary|^bit)/i', $type)) {
            $hex = bin2hex($value);
            return $driver === 'sqlite' ? "X'$hex'" : "0x$hex";
        }

        $quoted = $connection->getPdo()->quote($value);
        if ($quoted === false) {
            throw new Exception('Unable to quote a database value for the backup.');
        }

        return $quoted;
    }

    private function identifier(string $name, string $driver): string
    {
        return $driver === 'sqlite' ? $this->sqliteIdentifier($name) : $this->mysqlIdentifier($name);
    }

    private function mysqlIdentifier(string $name): string
    {
        return '`' . str_replace('`', '``', $name) . '`';
    }

    private function sqliteIdentifier(string $name): string
    {
        return '"' . str_replace('"', '""', $name) . '"';
    }

    private function write($stream, string $contents): void
    {
        if (fwrite($stream, $contents) !== strlen($contents)) {
            throw new Exception('Unable to write the complete database dump. Check available storage space.');
        }
    }
}
